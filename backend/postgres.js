// Keep the small statement API shared with local SQLite; values stay parameterized.
function postgresSql(sql) {
  let index = 0;
  return sql
    .replace(/strftime\('%Y-%m-%dT%H:%M:%fZ','now','-1 minute'\)/g, "to_char((clock_timestamp() - interval '1 minute') AT TIME ZONE 'UTC', 'YYYY-MM-DD\"T\"HH24:MI:SS.MS\"Z\"')")
    .replace(/strftime\('%Y-%m-%dT%H:%M:%fZ','now'\)/g, "to_char(clock_timestamp() AT TIME ZONE 'UTC', 'YYYY-MM-DD\"T\"HH24:MI:SS.MS\"Z\"')")
    .replace(/WHERE username=\?/g, 'WHERE lower(username)=lower(?)')
    .replace(/\?/g, () => '$' + ++index);
}

const timestamp = `TEXT NOT NULL DEFAULT (to_char(clock_timestamp() AT TIME ZONE 'UTC', 'YYYY-MM-DD"T"HH24:MI:SS.MS"Z"'))`;
const schema = [
  `CREATE TABLE IF NOT EXISTS users (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username TEXT NOT NULL, password_hash TEXT NOT NULL,
    role TEXT NOT NULL DEFAULT 'user' CHECK(role IN ('user','admin')),
    created_at ${timestamp})`,
  'CREATE UNIQUE INDEX IF NOT EXISTS users_username_lower ON users(lower(username))',
  `CREATE TABLE IF NOT EXISTS sessions (
    token_hash TEXT PRIMARY KEY, user_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    expires_at BIGINT NOT NULL)`,
  `CREATE TABLE IF NOT EXISTS articles (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title TEXT NOT NULL, content TEXT NOT NULL, tags TEXT NOT NULL DEFAULT '[]',
    author_id INTEGER NOT NULL REFERENCES users(id), created_at ${timestamp}, updated_at ${timestamp})`,
  `CREATE TABLE IF NOT EXISTS comments (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    article_id INTEGER NOT NULL REFERENCES articles(id) ON DELETE CASCADE,
    user_id INTEGER NOT NULL REFERENCES users(id), content TEXT NOT NULL, created_at ${timestamp})`,
  'CREATE INDEX IF NOT EXISTS comments_article ON comments(article_id)',
  `CREATE TABLE IF NOT EXISTS auth_attempts (
    key TEXT PRIMARY KEY, count INTEGER NOT NULL, expires_at BIGINT NOT NULL)`,
];

function createPostgresDatabase(pool, { initialize = true } = {}) {
  const ready = initialize
    ? (async () => { for (const statement of [...schema, ...require('./account-schema').postgresAccountMigrations]) await pool.query(statement); })()
    : Promise.resolve();
  // Startup and the request middleware both await this promise.
  ready.catch(() => {});
  const normalize = row => row && Object.fromEntries(Object.entries(row).map(([key, value]) =>
    [key, (key === 'n' || key === 'comment_count') ? Number(value) : value]));
  return {
    ready,
    async close() { await pool.end(); },
    prepare(sql) {
      const query = postgresSql(sql);
      return {
        async get(...values) { await ready; return normalize((await pool.query(query, values)).rows[0]); },
        async all(...values) { await ready; return (await pool.query(query, values)).rows.map(normalize); },
        async run(...values) {
          await ready;
          const insert = /^INSERT INTO (users|articles|comments)\b/i.test(query);
          const result = await pool.query(query + (insert ? ' RETURNING id' : ''), values);
          return { changes: result.rowCount, lastInsertRowid: result.rows[0]?.id };
        },
      };
    },
  };
}

module.exports = { createPostgresDatabase };
